import '../domain/audit.dart';
import '../domain/enums.dart';
import '../domain/match_data.dart';
import '../domain/selection.dart';
import 'engine_config.dart';
import 'markets/markets.dart';

/// VISA A — MARKET & IDENTITY. Outcomes: PASS, FAIL, UNKNOWN.
VisaStageResult evaluateVisaA(Selection s, EngineConfig cfg, DateTime nowUtc) {
  final f = <Finding>[];
  void ok(String t) => f.add(Finding(FindingLevel.ok, t));
  void unknown(String t) => f.add(Finding(FindingLevel.unknown, t));
  void fail(String t) => f.add(Finding(FindingLevel.fail, t));

  // Teams.
  final home = s.homeTeam.trim(), away = s.awayTeam.trim();
  if (home.isEmpty || away.isEmpty) {
    unknown('Home and away teams must both be identified.');
  } else if (home.toLowerCase() == away.toLowerCase()) {
    fail('Home and away team are identical — invalid fixture identity.');
  } else {
    ok('Fixture identified: $home (home) vs $away (away).');
  }

  // Competition.
  if (s.league.trim().isEmpty) {
    unknown('League / competition is missing.');
  } else {
    ok('Competition: ${s.league}${s.country.isNotEmpty ? ' (${s.country})' : ''}.');
  }

  // Kickoff.
  final ko = s.kickoff;
  if (ko == null) {
    unknown('Match date and kickoff time are missing.');
  } else if (!ko.isAfter(nowUtc)) {
    fail('Kickoff time has passed — a pre-match audit is no longer valid.');
  } else {
    ok('Kickoff confirmed in the future.');
  }

  // Market definition and settlement rules.
  final ev = MarketRegistry.of(s.market.type);
  final v = ev.validate(s.market);
  if (!v.ok) {
    for (final p in v.problems) {
      unknown('Market definition incomplete: $p');
    }
  } else {
    ok('Market: ${ev.describe(s.market, home, away)}.');
    ok('Settlement rule: ${ev.winCondition(s.market, home, away)}');
    f.add(Finding(FindingLevel.info, 'FAILURE EVENT: ${ev.failCondition(s.market, home, away)}'));
  }

  // Odds.
  final odds = s.odds;
  if (odds == null) {
    unknown('Decimal odds are missing.');
  } else if (odds <= 1.0) {
    fail('Decimal odds ${odds.toStringAsFixed(2)} are invalid (must exceed 1.00).');
  } else if (odds < cfg.minOdds || odds > cfg.maxOdds) {
    fail('Decimal odds ${odds.toStringAsFixed(2)} are outside the accepted range '
        '${cfg.minOdds}–${cfg.maxOdds}.');
  } else {
    ok('Decimal odds ${odds.toStringAsFixed(2)}'
        '${s.oddsSource.isNotEmpty ? ' (${s.oddsSource})' : ''}.');
  }
  if (odds != null) {
    final t = s.oddsUpdatedAt;
    if (t == null) {
      unknown('Odds timestamp missing — cannot confirm the price is current.');
    } else {
      final ageH = nowUtc.difference(t).inMinutes / 60.0;
      if (ageH > cfg.oddsMaxAgeHours) {
        unknown('Odds are stale (${ageH.toStringAsFixed(1)} h old; limit ${cfg.oddsMaxAgeHours} h).');
      }
    }
  }

  // Historical evidence availability, identity and currency.
  void checkHistory(String label, String team, List<HistoricalMatch> hist) {
    if (hist.isEmpty) {
      unknown('No historical matches recorded for $team ($label).');
      return;
    }
    final mismatched = hist.where((m) => m.sideOf(team) == null).length;
    if (mismatched > 0) {
      unknown('$mismatched $label record(s) do not include "$team" — identity mismatch; fix team names.');
    }
    final latest = hist.map((m) => m.date).reduce((a, b) => a.isAfter(b) ? a : b);
    final ref = ko ?? nowUtc;
    final age = ref.difference(latest).inDays;
    if (age > cfg.historyMaxAgeDays) {
      unknown('$team history is not current: latest match is $age days before kickoff '
          '(limit ${cfg.historyMaxAgeDays}).');
    }
    if (hist.any((m) => !m.date.isBefore(ref))) {
      fail('$label contains a match dated on/after the audited kickoff.');
    }
  }

  checkHistory('home-team history', home, s.homeHistory);
  checkHistory('away-team history', away, s.awayHistory);

  // Provenance — synthetic or model-generated data can never support approval.
  final all = [...s.homeHistory, ...s.awayHistory];
  if (s.origin == DataOrigin.synthetic || all.any((m) => m.origin == DataOrigin.synthetic)) {
    fail('Selection uses SYNTHETIC TEST DATA — it can never be approved.');
  }
  if (all.any((m) => m.origin == DataOrigin.modelGenerated)) {
    fail('Historical records generated by an AI model are not evidence.');
  }

  final outcome = f.any((x) => x.level == FindingLevel.fail)
      ? VisaOutcome.fail
      : f.any((x) => x.level == FindingLevel.unknown)
          ? VisaOutcome.unknown
          : VisaOutcome.pass;
  return VisaStageResult(stage: 'A', title: 'MARKET & IDENTITY', outcome: outcome, findings: f);
}
